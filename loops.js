//for loop
console.log("this is a for loop");
for(let i=0; i<9; i++){
    console.log(i);
}
//while loop
console.log("this is a while loop")
let j=9
while(j>0){
    console.log(j);
    j--;
}
//do while loop
console.log("this is a do while loop")
let k = 3
do{
    console.log(k);
    k++
} while(k<9)